#!/usr/bin/env python3
"""Build a CJK web font containing exactly the characters the site uses.

    python3 tools/build-font.py

Scans every XML file under XML/ (texts, notes, authority files, site.xml) for CJK
characters, subsets the locally installed Noto Serif CJK SC (SIL Open Font License) to
those characters, and writes:
    docs/fonts/rs-serif-cjk.woff2        regular weight
    docs/fonts/rs-serif-cjk-bold.woff2   bold weight, if the bold face is installed
    css/font-cjk.css                     the @font-face rules the pages inline
The family is renamed "RS Serif CJK" as the OFL requires for a modified font.
Run it before build.py whenever new Chinese text is added.
"""
import re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONTS = {
    "regular": ("/usr/share/fonts/opentype/noto/NotoSerifCJK-Regular.ttc", 2, "400"),
    "bold":    ("/usr/share/fonts/opentype/noto/NotoSerifCJK-Bold.ttc",    2, "700"),
}
CJK = re.compile(r"[⺀-⿟　-〿㐀-䶿一-鿿豈-﫿＀-￯\U00020000-\U0003134F]")


def main():
    chars = set()
    for f in ROOT.glob("XML/**/*.xml"):
        chars.update(CJK.findall(f.read_text(encoding="utf-8")))
    chars.update("　，。、；：？！「」『』（）《》〈〉—…·")
    text = "".join(sorted(chars))
    out_dir = ROOT / "docs" / "fonts"; out_dir.mkdir(parents=True, exist_ok=True)
    css = ["/* Generated by tools/build-font.py: Noto Serif CJK SC (SIL OFL 1.1) subset to the characters this site uses, renamed RS Serif CJK. */"]
    for weight, (path, index, css_weight) in FONTS.items():
        if not Path(path).exists():
            print(f"{weight}: {path} not installed, skipped"); continue
        out = out_dir / (f"rs-serif-cjk{'' if weight == 'regular' else '-' + weight}.woff2")
        subprocess.run([sys.executable, "-m", "fontTools.subset", path, f"--font-number={index}",
                        f"--text={text}", "--flavor=woff2", f"--output-file={out}",
                        "--layout-features=*", "--name-IDs=*", "--no-hinting", "--desubroutinize"], check=True)
        css.append(f'@font-face {{ font-family: "RS Serif CJK"; font-weight: {css_weight}; font-display: swap; src: url("FONTROOT/fonts/{out.name}") format("woff2"); }}')
        print(f"{weight}: {len(chars)} characters → {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
    (ROOT / "css" / "font-cjk.css").write_text("\n".join(css) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
